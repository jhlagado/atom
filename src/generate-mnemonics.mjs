import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { MNEMONICS, packRadix40 } from "./abi.mjs";

const entries = MNEMONICS.flatMap((name, ordinal) => {
  if (name === null) return [];
  if (name.length > 4) throw new Error(`mnemonic exceeds four characters: ${name}`);
  const [first, second] = packRadix40(name);
  return [{ name, ordinal, first, second, secondHigh: second >>> 8 }];
}).sort((left, right) => left.ordinal - right.ordinal);

entries.forEach(({ ordinal }, index) => {
  if (ordinal !== index + 1) throw new Error("mnemonic ordinals must be dense from one");
});

const lines = [
  "; Generated by src/generate-mnemonics.mjs. Do not edit.",
  `AtomMnemonicCount: .equ ${entries.length}`,
  "AtomMnemonicTable:",
  ...entries.flatMap(({ name, ordinal, first, secondHigh }) => [
    `            .dw  $${first.toString(16).padStart(4, "0").toUpperCase()}`,
    `            .db  $${secondHigh.toString(16).padStart(2, "0").toUpperCase()} ; ${ordinal}: ${name}`,
  ]),
  "AtomMnemonicTableEnd:",
  "",
];

const target = fileURLToPath(new URL("../asm/atom-mnemonics.inc", import.meta.url));
writeFileSync(target, lines.join("\n"));

const operandEntries = [
  ["B", "AtomOpB"], ["C", "AtomParserGenericC"], ["D", "AtomOpD"],
  ["E", "AtomOpE"], ["H", "AtomOpH"], ["L", "AtomOpL"], ["A", "AtomOpA"],
  ["BC", "AtomOpBC"], ["DE", "AtomOpDE"], ["HL", "AtomOpHL"],
  ["SP", "AtomOpSP"], ["AF", "AtomOpAF"], ["IX", "AtomOpIX"],
  ["IY", "AtomOpIY"], ["IXH", "AtomOpIXH"], ["IXL", "AtomOpIXL"],
  ["IYH", "AtomOpIYH"], ["IYL", "AtomOpIYL"], ["I", "AtomOpI"],
  ["R", "AtomOpR"], ["NZ", "AtomOpNZ"], ["Z", "AtomOpZ"],
  ["NC", "AtomOpNC"], ["PO", "AtomOpPO"], ["PE", "AtomOpPE"],
  ["P", "AtomOpP"], ["M", "AtomOpM"],
].map(([name, operandClass]) => ({ name, operandClass, key: packRadix40(name)[0] }))
  .sort((left, right) => left.key - right.key);

const operandLines = [
  "; Generated by src/generate-mnemonics.mjs. Do not edit.",
  `AtomParserOperandWordCount: .equ ${operandEntries.length}`,
  "AtomParserOperandWordTable:",
  ...operandEntries.flatMap(({ name, operandClass, key }) => [
    `            .dw  $${key.toString(16).padStart(4, "0").toUpperCase()}`,
    `            .db  ${operandClass} ; ${name}`,
  ]),
  "AtomParserOperandWordTableEnd:",
  "",
];

const operandTarget = fileURLToPath(new URL("../asm/atom-operands.inc", import.meta.url));
writeFileSync(operandTarget, operandLines.join("\n"));
