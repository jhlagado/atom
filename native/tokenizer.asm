;==============================================================================
;  Streaming tokenizer
;==============================================================================
;
;  Read one prepared source part through the source-byte service and publish
;  names, numbers, strings, punctuation, line endings and end of part. Lexeme
;  bytes remain in a fixed buffer only until the next tokenizer call.
;
;  Principal entries:
;    TK_RESET  select a source part and reset its logical position
;    TK_SPEEK  inspect the next source byte without consuming it
;    TK_STAKE  consume one byte into the current token buffer
;    TK_NEXT   publish the next token record
;
;  TK_SREAD is the platform source seam. The checked core contains the bounded
;  memory implementation below. Native platform builders replace only the
;  explicitly marked body with a jump to their source provider.

