;@ROUTINE IN A,HL,DE OUT A,IX,CARRY CLOBBERS SIGN,PARITY,HALFCARRY,ZERO
TK_RESET:
PUSH AF
PUSH HL
PUSH DE
EX   DE,HL
OR   A
SBC  HL,DE
JR   C,.RBSRANGE
LD   (TK_SEND),HL
POP  DE
POP  HL
POP  AF
LD   (TK_SPART),A
LD   (TK_SRCBA),HL
XOR  A
LD   (TK_SCURS),A
LD   (TK_SCURS+1),A
LD   (TK_SOSTA),A
LD   (TK_SOSTA+1),A
LD   (TK_LHTOK),A
LD   (TK_EPEND),A
LD   (TK_ESTAT),A
LD   (TK_REC+TK_KOFF),A
LD   IX,TK_REC
RET
.RBSRANGE:
POP  DE
POP  HL
POP  AF
.BSRANGE:
LD   A,TK_SBSRA
SCF
RET
;@ROUTINE OUT A,CARRY,ZERO CLOBBERS DE,HL,SIGN,PARITY,HALFCARRY
TK_SPEEK:
LD   HL,(TK_SCURS)
LD   DE,(TK_SEND)
OR   A
SBC  HL,DE
JR   Z,.SPEOF
ADD  HL,DE
.SRCPEEKB:
LD   A,(TK_SPART)
CALL TK_SREAD
OR   A
RET
.SPEOF:
SCF
RET
;@@ATOM_SOURCE_READ_BEGIN@@
;@ROUTINE IN A,HL OUT A,CARRY,ZERO CLOBBERS DE,HL,SIGN,PARITY,HALFCARRY
TK_SREAD:
LD   DE,(TK_SRCBA)
ADD  HL,DE
LD   A,(HL)
OR   A
RET
;@@ATOM_SOURCE_READ_END@@
;@ROUTINE OUT A,CARRY,ZERO CLOBBERS DE,HL,SIGN,PARITY,HALFCARRY
TK_STAKE:
PUSH BC
CALL TK_SPEEK
JR   C,.STEOF
LD   D,A
LD   HL,(TK_SCURS)
INC  HL
LD   (TK_SCURS),HL
LD   HL,(TK_SOSTA)
INC  HL
LD   (TK_SOSTA),HL
LD   A,(TK_BCNT)
LD   C,A
LD   B,0
LD   HL,TK_TBUF
ADD  HL,BC
LD   A,D
LD   (HL),A
LD   (TK_PREV),A
LD   A,(TK_BCNT)
INC  A
LD   (TK_BCNT),A
LD   A,D
POP  BC
OR   A
RET
.STEOF:
POP  BC
SCF
RET
;@ROUTINE OUT CARRY,ZERO CLOBBERS A,HL,SIGN,PARITY,HALFCARRY
TK_BEG:
LD   HL,TK_TBUF
LD   (TK_SPTR),HL
LD   HL,(TK_SOSTA)
LD   (TK_SOFF1),HL
XOR  A
LD   (TK_BCNT),A
LD   (TK_SLEN),A
LD   (TK_SVAL),A
LD   (TK_SVAL+1),A
RET
;@ROUTINE IN A OUT A,IX,CARRY CLOBBERS HL,SIGN,PARITY,HALFCARRY,ZERO
TK_CMT:
LD   (TK_REC+TK_KOFF),A
LD   A,(TK_SPART)
LD   (TK_REC+TK_POFF),A
LD   HL,(TK_SOFF1)
LD   (TK_REC+TK_SOFF),HL
LD   HL,(TK_SPTR)
LD   (TK_REC+TK_LOFF),HL
LD   A,(TK_SLEN)
LD   (TK_REC+TK_LOFF1),A
LD   HL,(TK_SVAL)
LD   (TK_REC+TK_VOFF),HL
LD   IX,TK_REC
LD   A,(TK_REC+TK_KOFF)
OR   A
RET
;@ROUTINE IN A OUT A,IX,CARRY CLOBBERS HL,ZERO,SIGN,PARITY,HALFCARRY
TK_FIN:
PUSH AF
LD   A,1
LD   (TK_LHTOK),A
POP  AF
JR   TK_CMT
;@ROUTINE IN A OUT A,CARRY CLOBBERS HL,HALFCARRY,SIGN,PARITY,ZERO
