;@ROUTINE IN A OUT A CLOBBERS CARRY,ZERO,SIGN,PARITY,HALFCARRY
CP_PUTC:
PUSH BC
PUSH DE
PUSH HL
LD   E,A
LD   C,2
CALL CP_BDOS
POP  HL
POP  DE
POP  BC
RET
;@ROUTINE IN A OUT A CLOBBERS BC,HL,CARRY,ZERO,SIGN,PARITY,HALFCARRY
